import { isPlayerSkillKey } from '../player-skills';
import type { FoundationPlayerState } from './types';

function isRecord(value: unknown): value is Record<string, any> {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function developmentNumber(value: unknown, min: number, max: number): number {
  const parsed =
    typeof value === 'number'
      ? value
      : typeof value === 'string' && value.trim().length > 0
        ? Number(value)
        : Number.NaN;
  if (!Number.isFinite(parsed) || parsed < min || parsed > max) {
    throw new Error('FOUNDATION_PLAYER_DEVELOPMENT_INVALID');
  }
  return parsed;
}

function assertDevelopmentSkillMap(
  player: Record<string, any>,
  field: 'proStats' | 'proTalents' | 'trainingProgress' | 'skillCaps' | 'skillInclinations',
  min: number,
  max: number,
): void {
  const value = player[field];
  // Missing/null maps are accepted for legacy player records. A present value
  // must be a record so normalization cannot spread strings or arrays.
  if (value === undefined || value === null) return;
  if (!isRecord(value)) throw new Error('FOUNDATION_PLAYER_DEVELOPMENT_INVALID');

  for (const [skill, rawValue] of Object.entries(value)) {
    if (!isPlayerSkillKey(skill)) {
      throw new Error('FOUNDATION_PLAYER_DEVELOPMENT_INVALID');
    }
    developmentNumber(rawValue, min, max);
  }
}

/**
 * Validate persisted player-development data before Foundation actions can
 * normalize, train, score or rewrite a roster. Partial skill maps remain
 * compatible with older records; malformed maps and out-of-domain values do
 * not silently become zero or disappear during object spreading.
 */
export function assertFoundationPlayerDevelopmentRecord(value: unknown): void {
  if (!isRecord(value)) throw new Error('FOUNDATION_PLAYER_DEVELOPMENT_INVALID');

  assertDevelopmentSkillMap(value, 'proStats', 0, 100);
  assertDevelopmentSkillMap(value, 'proTalents', 0, 100);
  assertDevelopmentSkillMap(value, 'trainingProgress', 0, 1);
  assertDevelopmentSkillMap(value, 'skillCaps', 0, 100);
  assertDevelopmentSkillMap(value, 'skillInclinations', 0, 100);

  for (const field of ['trainingPropensity', 'physical', 'resilience'] as const) {
    const rawValue = value[field];
    if (rawValue === undefined || rawValue === null) continue;
    developmentNumber(rawValue, 0, 100);
  }
}

/**
 * Read a canonical Foundation roster without silently converting malformed
 * stored data into an empty squad. Player IDs are required and unique because
 * lineup, training, match and market flows all address players by ID.
 */
export function readFoundationRoster(value: unknown): FoundationPlayerState[] {
  if (!Array.isArray(value)) throw new Error('FOUNDATION_ROSTER_INVALID');

  const ids = new Set<string>();
  for (const player of value) {
    if (!isRecord(player) || typeof player.id !== 'string') {
      throw new Error('FOUNDATION_ROSTER_INVALID');
    }
    const id = player.id.trim();
    if (!id || id !== player.id || id.length > 128 || ids.has(id)) {
      throw new Error('FOUNDATION_ROSTER_INVALID');
    }
    ids.add(id);
    assertFoundationPlayerDevelopmentRecord(player);
  }

  return value as FoundationPlayerState[];
}

/**
 * Shared strict parser for persisted Foundation currency and treasury values.
 * Missing legacy values remain zero; blank strings and malformed numbers do
 * not silently become a free balance.
 */
export function readFoundationNonNegativeInteger(value: unknown, errorCode: string): number {
  if (value === undefined || value === null) return 0;
  if (typeof value === 'string' && value.trim().length === 0) throw new Error(errorCode);
  const parsed = typeof value === 'number' || typeof value === 'string' ? Number(value) : NaN;
  if (!Number.isSafeInteger(parsed) || parsed < 0) throw new Error(errorCode);
  return parsed;
}

export function readFoundationStaffSalary(value: unknown): number {
  return readFoundationNonNegativeInteger(value, 'FOUNDATION_SALARY_INVALID');
}

const FOUNDATION_STAFF_ROLES = new Set([
  'recruiter',
  'coach',
  'analyst',
  'scout',
  'doctor',
  'financier',
]);

/**
 * Validate the persisted identity and payroll contract for one staff member.
 * Missing salary must not silently become zero: every hired member has a
 * positive, safe-integer salary generated by the staff market.
 */
export interface FoundationStaffMemberRecord extends Record<string, any> {
  id: string;
  role: string;
  salary: number | string;
}

/**
 * Validate the persisted identity and payroll contract for one staff member.
 * Missing salary must not silently become zero: every hired member has a
 * positive, safe-integer salary generated by the staff market.
 */
export function readFoundationStaffMember(value: unknown, expectedRole?: string): FoundationStaffMemberRecord {
  if (!isRecord(value)) throw new Error('FOUNDATION_STAFF_INVALID');

  const id = typeof value.id === 'string' ? value.id.trim() : '';
  const role = typeof value.role === 'string' ? value.role : '';
  const salary = readFoundationStaffSalary(value.salary);
  if (
    !id ||
    id !== value.id ||
    id.length > 128 ||
    !FOUNDATION_STAFF_ROLES.has(role) ||
    (expectedRole !== undefined && role !== expectedRole) ||
    salary <= 0
  ) {
    throw new Error('FOUNDATION_STAFF_INVALID');
  }

  return value as FoundationStaffMemberRecord;
}

/**
 * Null/missing staff slots are valid. Every occupied slot must contain a
 * canonical staff identity with a matching role and a positive payroll amount.
 * This prevents malformed staff from receiving bonuses or escaping payroll.
 */
export function readFoundationStaff(value: unknown): Record<string, any> {
  if (value === undefined || value === null) return {};
  if (!isRecord(value)) throw new Error('FOUNDATION_STAFF_INVALID');

  for (const [role, member] of Object.entries(value)) {
    if (!FOUNDATION_STAFF_ROLES.has(role)) throw new Error('FOUNDATION_STAFF_INVALID');
    if (member === null || member === undefined) continue;
    readFoundationStaffMember(member, role);
  }

  return value;
}
