export type MatchRole = 'Carry' | 'Midlaner' | 'Tank' | 'Jungler' | 'Support';
export type MatchSide = 'home' | 'away';
export type TacticalDirection = 'easy' | 'mid' | 'hard' | 'balanced' | 'left' | 'center' | 'right';
export type TacticalTempo = 'slow' | 'medium' | 'fast' | 'careful' | 'balanced';
export type TacticalStyle = 'control' | 'balanced' | 'aggressive';
export type TacticalPressing = 'low' | 'medium' | 'high';
export type TacticalAggression = 'low' | 'medium' | 'high';
export type TacticalRange = 'close' | 'medium' | 'long';

export interface TacticalSettings {
  direction?: TacticalDirection;
  tempo?: TacticalTempo;
  style?: TacticalStyle;
  pressing?: TacticalPressing;
  aggression?: TacticalAggression;
  risk?: 'cautious' | 'balanced' | 'aggressive';
  rigidity?: 'low' | 'medium' | 'high';
  range?: TacticalRange;
  lineSettings?: Record<string, 'passive' | 'standard' | 'active'>;
}

export interface MatchTeamSnapshot {
  id?: string;
  name: string;
  players?: any[];
  strategy?: string;
  tactics?: TacticalSettings;
  staffBonus?: number;
  infraBonus?: number;
  analystBonus?: number;
  synergy?: number;
  /** Optional manager-configured draft preferences; absent values use deterministic safe defaults. */
  draftPreferences?: { preferredHeroes?: string[]; bannedHeroes?: string[]; rolePreferences?: Record<string, string[]> };
}

